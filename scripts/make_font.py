GLYPHS.update(ARROWS)

# 並び順 (= C 側の glyph_of() が返す番号)。ここを変えたら c_text.c も直す。
# 末尾の 8 字 (a-d、f-i) は矢印で、番号 41-48 になる。
ORDER = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-.!=abcdfghi"


def rows_of(ch: str):
    art = GLYPHS[ch]
    out = []
    for r in range(7):
        line = art[r] if r < len(art) else ""
        v = 0
        for c, p in enumerate(line):
            if p == '#':
                v |= 0x80 >> c
        out.append(v)
    out.append(0)           # 8 行目は行間
    return out


def main() -> None:
    if len(sys.argv) != 2:
        print("usage: make_font.py <out.h>", file=sys.stderr)
        sys.exit(1)

    if len(set(ORDER)) != len(ORDER):
        print("make_font: ORDER に同じ字が 2 回ある", file=sys.stderr)
        sys.exit(1)
    for ch in ORDER:
        if ch not in GLYPHS:
            print(f"make_font: 字形が無い: {ch!r}", file=sys.stderr)
            sys.exit(1)
    # 字形は 5 dot 幅 x 7 line に収まっていること (はみ出した行や列は黙って
    # 落ちるか字間に食い込むので、ここで止める)
    for ch, art in GLYPHS.items():
        if len(art) > GLYPH_ROWS or any(len(line) > GLYPH_COLS for line in art):
            print(f"make_font: 字形 {ch!r} が {GLYPH_COLS} dot x {GLYPH_ROWS} line "
                  f"を超える", file=sys.stderr)
            sys.exit(1)

    lines = [
        "/* build/font.h — scripts/make_font.py が生成 (手で直さない) */",
        "#ifndef FONT_H",
        "#define FONT_H",
        "",
        "/* 8x8 の字形。1 字 8 byte、bit7 が左端。番号は c_text.c の",
        f" * glyph_of() と対で決まる (並び: \"{ORDER}\")。 */",
        f"#define FONT_GLYPHS  {len(ORDER)}",
        "",
        "const unsigned char font8[FONT_GLYPHS * 8] = {",
    ]
    for i, ch in enumerate(ORDER):
        vals = ", ".join(f"0x{v:02X}" for v in rows_of(ch))
        if ch == ' ':
            name = "SPACE"
        elif ch in ARROWS:
            name = f"ARROW {ord(ch) - ord('a') + 1}"
        else:
            name = ch
        lines.append(f"    {vals},   /* {i:2d} {name} */")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"make_font: OK — {sys.argv[1]} ({len(ORDER)} 字 x 8 byte)")


if __name__ == "__main__":
    main()
